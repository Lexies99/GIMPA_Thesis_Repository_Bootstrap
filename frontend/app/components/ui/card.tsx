  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, style, ...props }, ref) => (
  <div
    ref={ref}
    className={`rounded-xl border ${className || ""}`}
    style={{
      backgroundColor: "var(--bg-card)",
      borderColor: "var(--border-color)",
      color: "var(--text-main)",
      ...style,
    }}
    {...props}
  />
))
Card.displayName = "Card"

